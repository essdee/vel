package build

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strings"
)

// GenerateWrappers creates cap/* wrapper packages in _build for tier 2 imports.
// Returns a map from original import path to wrapper import path.
func GenerateWrappers(buildDir string, tier2Imports map[string]bool) (map[string]string, error) {
	rewriteMap := make(map[string]string)

	for pkg := range tier2Imports {
		if BlacklistedPackages[pkg] {
			continue
		}

		wrapperImport := "vel/cap/" + pkg
		pkgName := filepath.Base(pkg)

		wrapperDir := filepath.Join(buildDir, "cap", pkg)
		if err := os.MkdirAll(wrapperDir, 0755); err != nil {
			return nil, fmt.Errorf("creating wrapper dir for %s: %w", pkg, err)
		}

		code := generateWrapperCode(pkg, pkgName)
		wrapperFile := filepath.Join(wrapperDir, pkgName+".go")
		if err := os.WriteFile(wrapperFile, []byte(code), 0644); err != nil {
			return nil, fmt.Errorf("writing wrapper for %s: %w", pkg, err)
		}

		rewriteMap[pkg] = wrapperImport
	}

	return rewriteMap, nil
}

// generateWrapperCode parses the real stdlib package and re-exports its public API,
// omitting blacklisted functions and adding cap.Check guards where possible.
func generateWrapperCode(pkg, pkgName string) string {
	blacklistSet := make(map[string]bool)
	if fns, ok := BlacklistedFunctions[pkg]; ok {
		for _, fn := range fns {
			blacklistSet[fn] = true
		}
	}

	goroot := os.Getenv("GOROOT")
	if goroot == "" {
		goroot = "/usr/local/go"
	}
	pkgDir := filepath.Join(goroot, "src", pkg)

	fset := token.NewFileSet()
	pkgs, err := parser.ParseDir(fset, pkgDir, func(fi os.FileInfo) bool {
		name := fi.Name()
		return strings.HasSuffix(name, ".go") &&
			!strings.HasSuffix(name, "_test.go") &&
			!strings.Contains(name, "_other") // skip platform files that might not parse
	}, 0)
	if err != nil {
		return fallbackWrapper(pkg, pkgName)
	}

	var astPkg *ast.Package
	for name, p := range pkgs {
		if name == pkgName {
			astPkg = p
			break
		}
	}
	if astPkg == nil {
		for _, p := range pkgs {
			astPkg = p
			break
		}
	}
	if astPkg == nil {
		return fallbackWrapper(pkg, pkgName)
	}

	typeSet := make(map[string]bool)
	varSet := make(map[string]bool)
	funcSet := make(map[string]bool)

	for _, file := range astPkg.Files {
		for _, decl := range file.Decls {
			switch d := decl.(type) {
			case *ast.GenDecl:
				for _, spec := range d.Specs {
					switch s := spec.(type) {
					case *ast.TypeSpec:
						if ast.IsExported(s.Name.Name) && s.TypeParams == nil {
							// Skip generic types (TypeParams != nil) — they cannot be aliased without instantiation.
							typeSet[s.Name.Name] = true
						}
					case *ast.ValueSpec:
						for _, name := range s.Names {
							if ast.IsExported(name.Name) {
								if d.Tok == token.VAR {
									varSet[name.Name] = true
								}
								// Skip consts - they need special handling
							}
						}
					}
				}
			case *ast.FuncDecl:
				if d.Recv != nil || !ast.IsExported(d.Name.Name) {
					continue
				}
				if blacklistSet[d.Name.Name] {
					continue
				}
				funcSet[d.Name.Name] = true
			}
		}
	}

	var b strings.Builder
	b.WriteString(fmt.Sprintf("// Code generated by vel build. DO NOT EDIT.\npackage %s\n\nimport (\n\treal %q\n\t\"vel/internal/cap\"\n)\n\n", pkgName, pkg))

	// Suppress unused import of cap
	b.WriteString("var _ = cap.Check\n\n")

	// Type aliases
	for t := range typeSet {
		b.WriteString(fmt.Sprintf("type %s = real.%s\n", t, t))
	}
	if len(typeSet) > 0 {
		b.WriteString("\n")
	}

	// Var re-exports
	for v := range varSet {
		b.WriteString(fmt.Sprintf("var %s = real.%s\n", v, v))
	}
	if len(varSet) > 0 {
		b.WriteString("\n")
	}

	// Function re-exports (as var references - preserves signature)
	// Blacklisted functions are omitted entirely
	for fn := range funcSet {
		b.WriteString(fmt.Sprintf("var %s = real.%s\n", fn, fn))
	}

	return b.String()
}

func fallbackWrapper(pkg, pkgName string) string {
	return fmt.Sprintf(`// Code generated by vel build. DO NOT EDIT.
// Fallback wrapper - could not parse package source.
package %s

import (
	_ %q
	"vel/internal/cap"
)

var _ = cap.Check
`, pkgName, pkg)
}
